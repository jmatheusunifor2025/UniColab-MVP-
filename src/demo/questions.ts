function item(
  id: string,
  text: string,
  type: Question['type'],
  area: string,
  year: number,
  difficulty: Question['difficulty'],
  alternatives: string[],
  correctAlternative: number,
  commentary: string,
  references: string,
  comments: Question['comments'] = [],
): Question {
  const justifications = alternatives.map((alternative, index) =>
    index === correctAlternative
      ? commentary
      : `A alternativa sobre “${alternative.slice(0, 72)}” não responde ao que o enunciado pede.`,
  );
  return {
    id,
    text,
    type,
    area,
    year,
    difficulty,
    alternatives,
    alternativeIds: alternatives.map((_, index) => Number(id.replace(/\D/g, '')) * 10 + index + 1),
    correctAlternative,
    justifications,
    hasJustification: true,
    commentary,
    references,
    comments,
  };
}

